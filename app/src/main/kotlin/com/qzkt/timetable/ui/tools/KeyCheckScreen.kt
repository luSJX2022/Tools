@OptIn(ExperimentalMaterial3Api::class)
@Composable
private fun CameraQrDialog(
    onDismiss: () -> Unit,
    onScanned: (String) -> Unit,
    onError: (String) -> Unit,
) {
    val context = LocalContext.current
    val lifecycleOwner = LocalLifecycleOwner.current
    var previewView by remember { mutableStateOf<PreviewView?>(null) }
    var cameraProvider by remember { mutableStateOf<ProcessCameraProvider?>(null) }
    var cameraError by remember { mutableStateOf<String?>(null) }
    val executor = remember { Executors.newSingleThreadExecutor() }
    val reader = remember {
        MultiFormatReader().apply {
            setHints(
                EnumMap<DecodeHintType, Any>(DecodeHintType::class.java).apply {
                    put(DecodeHintType.POSSIBLE_FORMATS, listOf(BarcodeFormat.QR_CODE))
                    put(DecodeHintType.TRY_HARDER, true)
                },
            )
        }
    }
    var delivered by remember { mutableStateOf(false) }

    LaunchedEffect(context) {
        try {
            cameraProvider = awaitCameraProvider(context)
        } catch (e: Exception) {
            val message = e.message ?: "相机初始化失败"
            cameraError = message
            onError(message)
        }
    }
    LaunchedEffect(cameraProvider, previewView, lifecycleOwner) {
        val provider = cameraProvider ?: return@LaunchedEffect
        val preview = previewView ?: return@LaunchedEffect
        try {
            val previewUseCase = Preview.Builder().build().also {
                it.surfaceProvider = preview.surfaceProvider
            }
            val analysis = ImageAnalysis.Builder()
                .setBackpressureStrategy(ImageAnalysis.STRATEGY_KEEP_ONLY_LATEST)
                .build()
                .also { useCase ->
                    useCase.setAnalyzer(executor) { image ->
                        val decoded = decodeQrFromCameraFrame(reader, image)
                        if (decoded != null && !delivered) {
                            delivered = true
                            ContextCompat.getMainExecutor(context).execute { onScanned(decoded) }
                        }
                    }
                }
            provider.unbindAll()
            provider.bindToLifecycle(
                lifecycleOwner,
                CameraSelector.DEFAULT_BACK_CAMERA,
                previewUseCase,
                analysis,
            )
        } catch (e: Exception) {
            val message = e.message ?: "无法启动相机预览"
            cameraError = message
            onError(message)
        }
    }
    DisposableEffect(Unit) {
        onDispose { executor.shutdown() }
    }
    DisposableEffect(cameraProvider) {
        onDispose {
            cameraProvider?.unbindAll()
        }
    }
    AlertDialog(
        onDismissRequest = onDismiss,
        confirmButton = {
            TextButton(onClick = onDismiss) { Text("关闭") }
        },
        title = { Text("扫描二维码") },
        text = {
            Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
                AndroidView(
                    factory = { viewContext ->
                        PreviewView(viewContext).apply {
                            layoutParams = ViewGroup.LayoutParams(
                                ViewGroup.LayoutParams.MATCH_PARENT,
                                480,
                            )
                            scaleType = PreviewView.ScaleType.FILL_CENTER
                            previewView = this
                        }
                    },
                    modifier = Modifier
                        .fillMaxWidth()
                        .height(300.dp),
                )
                Text(
                    cameraError ?: "将二维码放入取景框。扫描内容只会载入输入框，不会自动连接或运行。",
                    style = MaterialTheme.typography.bodySmall,
                )
            }
        },
    )
}

private suspend fun awaitCameraProvider(context: Context): ProcessCameraProvider =
    suspendCoroutine { continuation ->
        val future = ProcessCameraProvider.getInstance(context)
        future.addListener(
            {
                try {
                    continuation.resume(future.get())
                } catch (e: Exception) {
                    continuation.resumeWithException(e)
                }
            },
            ContextCompat.getMainExecutor(context),
        )
    }

private fun decodeQrFromCameraFrame(reader: MultiFormatReader, image: ImageProxy): String? {
    try {
        val plane = image.planes.firstOrNull() ?: return null
        val width = image.width
        val height = image.height
        val buffer = plane.buffer
        val bytes = ByteArray(width * height)
        for (row in 0 until height) {
            for (column in 0 until width) {
                bytes[row * width + column] =
                    buffer.get(row * plane.rowStride + column * plane.pixelStride)
            }
        }
        val source = PlanarYUVLuminanceSource(bytes, width, height, 0, 0, width, height, false)
        return runCatching { reader.decodeWithState(BinaryBitmap(HybridBinarizer(source))).text }
            .getOrNull()
    } finally {
        image.close()
        reader.reset()
    }
}

private fun decodeQrFromImage(context: Context, uri: android.net.Uri): String? {
    val bounds = BitmapFactory.Options().apply { inJustDecodeBounds = true }
    context.contentResolver.openInputStream(uri)?.use { BitmapFactory.decodeStream(it, null, bounds) }
        ?: throw IOException("无法读取所选图片")
    if (bounds.outWidth <= 0 || bounds.outHeight <= 0 ||
        bounds.outWidth.toLong() * bounds.outHeight > 80_000_000L
    ) {
        throw IOException("图片尺寸无效或过大")
    }
    val sample = Integer.highestOneBit(
        maxOf(bounds.outWidth / 3000, bounds.outHeight / 3000, 1),
    )
    val bitmap = context.contentResolver.openInputStream(uri)?.use {
        BitmapFactory.decodeStream(
            it,
            null,
            BitmapFactory.Options().apply { inSampleSize = sample },
        )
    } ?: throw IOException("无法解码所选图片")
    val width = bitmap.width
    val height = bitmap.height
    if (width <= 0 || height <= 0 || width.toLong() * height > 40_000_000L) {
        throw IOException("图片尺寸无效或过大")
    }
    val pixels = IntArray(width * height)
    bitmap.getPixels(pixels, 0, width, 0, 0, width, height)
    bitmap.recycle()
    val source = RGBLuminanceSource(width, height, pixels)
    val hints = mapOf(DecodeHintType.POSSIBLE_FORMATS to listOf(BarcodeFormat.QR_CODE))
    return runCatching {
        MultiFormatReader().apply { setHints(hints) }
            .decode(BinaryBitmap(HybridBinarizer(source))).text
    }.getOrNull()
}

private fun copyText(context: Context, label: String, value: String) {
    val clipboard = context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
    clipboard.setPrimaryClip(ClipData.newPlainText(label, value))
}

private val KeyCheckStatus.title: String
    get() = when (this) {
        KeyCheckStatus.VALID -> "有效"
        KeyCheckStatus.WARNING -> "提醒"
        KeyCheckStatus.INVALID -> "无效"
    }
