@OptIn(ExperimentalMaterial3Api::class)
@Composable
internal fun KeyCheckScreen(onBack: () -> Unit) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    var input by remember { mutableStateOf("") }
    var baseline by remember { mutableStateOf("") }
    var report by remember { mutableStateOf<KeyCheckReport?>(null) }
    var generated by remember { mutableStateOf<GeneratedWireGuardKeys?>(null) }
    var revealPrivateKey by remember { mutableStateOf(false) }
    var scannerOpen by remember { mutableStateOf(false) }
    var busy by remember { mutableStateOf(false) }
    var status by remember { mutableStateOf<String?>(null) }
    var error by remember { mutableStateOf<String?>(null) }
    var pendingJson by remember { mutableStateOf<String?>(null) }

    fun applyScannedText(value: String) {
        input = value.trim()
        report = null
        scannerOpen = false
        status = "二维码内容已在本机载入；请先确认来源，再点击验证"
    }

    val imagePicker = rememberLauncherForActivityResult(ActivityResultContracts.OpenDocument()) { uri ->
        if (uri != null) {
            scope.launch {
                busy = true
                error = null
                try {
                    val decoded = withContext(Dispatchers.IO) { decodeQrFromImage(context, uri) }
                    if (decoded.isNullOrBlank()) {
                        error = "图片中没有识别到二维码"
                    } else {
                        applyScannedText(decoded)
                    }
                } catch (e: CancellationException) {
                    throw e
                } catch (e: Exception) {
                    error = e.message ?: "读取二维码图片失败"
                } finally {
                    busy = false
                }
            }
        }
    }
    val cameraPermission = rememberLauncherForActivityResult(
        ActivityResultContracts.RequestPermission(),
    ) { granted ->
        if (granted) scannerOpen = true else error = "相机权限未授予，仍可从图片导入二维码"
    }
    val jsonExporter = rememberLauncherForActivityResult(
        ActivityResultContracts.CreateDocument("application/json"),
    ) { uri ->
        val json = pendingJson
        pendingJson = null
        if (uri != null && json != null) {
            runCatching {
                context.contentResolver.openOutputStream(uri)?.bufferedWriter(Charsets.UTF_8)?.use {
                    it.write(json)
                } ?: throw IOException("无法创建导出文件")
            }.onSuccess {
                status = "已导出不含原始密钥的 JSON 报告"
            }.onFailure {
                error = it.message ?: "导出报告失败"
            }
        }
    }

    DisposableEffect(Unit) {
        onDispose {
            input = ""
            baseline = ""
            generated = null
            report = null
        }
    }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("P2P 密钥验证器") },
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "返回")
                    }
                },
            )
        },
    ) { padding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .verticalScroll(rememberScrollState())
                .padding(horizontal = 16.dp, vertical = 10.dp),
            verticalArrangement = Arrangement.spacedBy(12.dp),
        ) {
            Card(
                colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.secondaryContainer),
                modifier = Modifier.fillMaxWidth(),
            ) {
                Text(
                    "完全离线处理 WireGuard 配置与密钥。私钥不会上传或保存；请勿把真实私钥发给他人。",
                    modifier = Modifier.padding(14.dp),
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSecondaryContainer,
                )
            }
            OutlinedTextField(
                value = input,
                onValueChange = {
                    input = it
                    report = null
                    generated = null
                },
                label = { Text("密钥 / WireGuard 配置") },
                placeholder = { Text("粘贴 .conf 配置或 Base64 密钥") },
                modifier = Modifier
                    .fillMaxWidth()
                    .height(220.dp),
                minLines = 6,
                maxLines = 12,
                textStyle = MaterialTheme.typography.bodySmall,
            )
            OutlinedTextField(
                value = baseline,
                onValueChange = {
                    baseline = it
                    report = null
                },
                label = { Text("已知指纹 / 对端公钥（可选）") },
                placeholder = { Text("SHA-256 指纹（至少 8 位）或 Base64 公钥") },
                modifier = Modifier.fillMaxWidth(),
                singleLine = true,
            )
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.spacedBy(8.dp),
            ) {
                Button(
                    enabled = !busy && input.isNotBlank(),
                    onClick = {
                        report = KeyCheckEngine.analyze(input, baseline)
                        status = "验证完成：所有处理均在本机进行"
                        error = null
                    },
                    modifier = Modifier.weight(1f),
                ) {
                    Icon(Icons.Default.Security, contentDescription = null)
                    Text(" 验证")
                }
                OutlinedButton(
                    enabled = !busy,
                    onClick = {
                        if (ContextCompat.checkSelfPermission(context, Manifest.permission.CAMERA) ==
                            PackageManager.PERMISSION_GRANTED
                        ) {
                            scannerOpen = true
                        } else {
                            cameraPermission.launch(Manifest.permission.CAMERA)
                        }
                    },
                    modifier = Modifier.weight(1f),
                ) {
                    Icon(Icons.Default.QrCodeScanner, contentDescription = null)
                    Text(" 扫码")
                }
            }
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.spacedBy(8.dp),
            ) {
                OutlinedButton(
                    enabled = !busy,
                    onClick = { imagePicker.launch(arrayOf("image/*")) },
                    modifier = Modifier.weight(1f),
                ) {
                    Icon(Icons.Default.Image, contentDescription = null)
                    Text(" 选图")
                }
                OutlinedButton(
                    enabled = !busy,
                    onClick = {
                        scope.launch {
                            busy = true
                            try {
                                val keys = withContext(Dispatchers.Default) { KeyCheckEngine.generateKeys() }
                                generated = keys
                                input = ""
                                report = null
                                revealPrivateKey = false
                                status = "已在本机生成密钥；私钥只在当前界面内存中暂存"
                            } catch (e: Exception) {
                                error = e.message ?: "生成密钥失败"
                            } finally {
                                busy = false
                            }
                        }
                    },
                    modifier = Modifier.weight(1f),
                ) {
                    Text("生成密钥")
                }
                OutlinedButton(
                    enabled = input.isNotBlank() || baseline.isNotBlank() || generated != null,
                    onClick = {
                        input = ""
                        baseline = ""
                        generated = null
                        report = null
                        status = "已清空"
                    },
                    modifier = Modifier.weight(1f),
                ) {
                    Text("清空")
                }
            }
            OutlinedButton(
                enabled = !busy,
                onClick = {
                    scope.launch {
                        busy = true
                        error = null
                        try {
                            val sampleKeys = withContext(Dispatchers.Default) {
                                KeyCheckEngine.generateKeys() to KeyCheckEngine.generateKeys()
                            }
                            input = """
                                [Interface]
                                PrivateKey = ${sampleKeys.first.privateKey}

                                [Peer]
                                PublicKey = ${sampleKeys.second.publicKey}
                                Endpoint = 203.0.113.42:51820
                                AllowedIPs = 10.0.0.0/24
                            """.trimIndent()
                            generated = null
                            report = null
                            status = "已载入示例配置（使用临时随机密钥与文档保留地址，不会连接网络）"
                        } catch (e: Exception) {
                            error = e.message ?: "创建示例失败"
                        } finally {
                            busy = false
                        }
                    }
                },
                modifier = Modifier.fillMaxWidth(),
            ) {
                Text("载入示例")
            }

            report?.let { result ->
                ReportCard(
                    report = result,
                    context = context,
                    onExport = { json ->
                        pendingJson = json
                        jsonExporter.launch("keycheck-report.json")
                    },
                )
            }
            generated?.let { keys ->
                GeneratedKeysCard(
                    keys = keys,
                    revealPrivateKey = revealPrivateKey,
                    onRevealChange = { revealPrivateKey = it },
                    onCopy = { label, value ->
                        copyText(context, label, value)
                        status = "$label 已复制到剪贴板"
                    },
                )
            }
            error?.let { Text(it, color = MaterialTheme.colorScheme.error) }
            status?.let { Text(it, color = MaterialTheme.colorScheme.primary) }
            Spacer(Modifier.height(20.dp))
        }
    }

    if (busy) {
        AlertDialog(
            onDismissRequest = {},
            confirmButton = {},
            title = { Text("正在处理") },
            text = { CircularProgressIndicator() },
        )
    }
    if (scannerOpen) {
        CameraQrDialog(
            onDismiss = { scannerOpen = false },
            onScanned = ::applyScannedText,
            onError = { error = it },
        )
    }
}

@Composable
private fun ReportCard(
    report: KeyCheckReport,
    context: Context,
    onExport: (String) -> Unit,
) {
    Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
        Text("验证结果", style = MaterialTheme.typography.titleMedium)
        Row(horizontalArrangement = Arrangement.spacedBy(14.dp)) {
            Text("有效 ${report.validCount}", color = MaterialTheme.colorScheme.primary)
            Text("提醒 ${report.warningCount}", color = MaterialTheme.colorScheme.tertiary)
            Text(
                "无效 ${report.invalidCount}",
                color = if (report.invalidCount > 0) MaterialTheme.colorScheme.error
                else MaterialTheme.colorScheme.onSurface,
            )
        }
        report.findings.forEach { finding ->
            Card(modifier = Modifier.fillMaxWidth()) {
                Column(
                    modifier = Modifier.padding(12.dp),
                    verticalArrangement = Arrangement.spacedBy(4.dp),
                ) {
                    Text(
                        "${finding.status.title} · ${finding.name}",
                        style = MaterialTheme.typography.titleSmall,
                    )
                    Text(finding.details, style = MaterialTheme.typography.bodySmall)
                    finding.fingerprint?.let {
                        Text(
                            "SHA-256 ${it.chunked(2).joinToString(":")}",
                            style = MaterialTheme.typography.labelSmall,
                        )
                    }
                }
            }
        }
        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            OutlinedButton(onClick = {
                copyText(context, "KeyCheck 报告", report.toText())
            }) {
                Icon(Icons.Default.ContentCopy, contentDescription = null)
                Text(" 复制报告")
            }
            OutlinedButton(onClick = { onExport(report.toRedactedJson()) }) {
                Text("下载 JSON")
            }
        }
        Text(
            "报告不会包含原始密钥或配置内容。",
            style = MaterialTheme.typography.bodySmall,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
        )
    }
}

